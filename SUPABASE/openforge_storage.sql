create table if not exists public.generated_docs (
	repository_name text primary key,
	document text not null,
	output_format text not null default 'markdown'
		check (output_format in ('markdown', 'json', 'html')),
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now()
);

create table if not exists public.repository_search_history (
	id bigint generated by default as identity primary key,
	query text not null,
	result_count integer not null default 0 check (result_count >= 0),
	results jsonb not null default '[]'::jsonb,
	searched_at timestamptz not null default now()
);

create index if not exists repository_search_history_searched_at_idx
	on public.repository_search_history (searched_at desc);

alter table public.generated_docs enable row level security;
alter table public.repository_search_history enable row level security;

grant usage on schema public to service_role;
grant select, insert, update, delete on public.generated_docs to service_role;
grant select, insert, update, delete on public.repository_search_history to service_role;
grant usage, select on sequence public.repository_search_history_id_seq to service_role;
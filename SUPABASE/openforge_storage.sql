create table if not exists public.developer_profiles (
	user_id uuid primary key references auth.users(id) on delete cascade,
	display_name text not null default '',
	github_username text not null default '',
	bio text not null default '',
	skills text[] not null default '{}',
	interests text[] not null default '{}',
	preferred_languages text[] not null default '{}',
	experience_level text not null default 'beginner'
		check (experience_level in ('beginner', 'intermediate', 'advanced')),
	contribution_goals text[] not null default '{}',
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now()
);

create table if not exists public.generated_docs (
	id bigint generated by default as identity primary key,
	user_id uuid references auth.users(id) on delete cascade,
	repository_name text not null,
	document text not null,
	output_format text not null default 'markdown'
		check (output_format in ('markdown', 'json', 'html')),
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now()
);

alter table public.generated_docs
	add column if not exists id bigint generated by default as identity;
alter table public.generated_docs
	add column if not exists user_id uuid references auth.users(id) on delete cascade;
alter table public.generated_docs drop constraint if exists generated_docs_pkey;
alter table public.generated_docs add constraint generated_docs_pkey primary key (id);
alter table public.generated_docs
	drop constraint if exists generated_docs_user_repository_key;
alter table public.generated_docs
	add constraint generated_docs_user_repository_key unique (user_id, repository_name);

create table if not exists public.repository_search_history (
	id bigint generated by default as identity primary key,
	user_id uuid references auth.users(id) on delete cascade,
	query text not null,
	result_count integer not null default 0 check (result_count >= 0),
	results jsonb not null default '[]'::jsonb,
	searched_at timestamptz not null default now()
);

alter table public.repository_search_history
	add column if not exists user_id uuid references auth.users(id) on delete cascade;

create index if not exists repository_search_history_searched_at_idx
	on public.repository_search_history (searched_at desc);
create index if not exists repository_search_history_user_searched_at_idx
	on public.repository_search_history (user_id, searched_at desc);

create table if not exists public.agent_chat_sessions (
	user_id uuid not null references auth.users(id) on delete cascade,
	session_id text not null,
	repository_id text not null default '',
	title text not null default 'New chat',
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),
	primary key (user_id, session_id)
);

create index if not exists agent_chat_sessions_user_updated_at_idx
	on public.agent_chat_sessions (user_id, updated_at desc);

create table if not exists public.agent_conversation_memory (
	user_id text not null,
	session_id text not null,
	repository_id text not null,
	messages jsonb not null default '[]'::jsonb,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),
	primary key (user_id, session_id)
);

create index if not exists agent_conversation_memory_updated_at_idx
	on public.agent_conversation_memory (updated_at desc);

create table if not exists public.agent_response_cache (
	cache_key text primary key,
	user_id uuid references auth.users(id) on delete cascade,
	agent_name text not null,
	response jsonb not null,
	expires_at timestamptz not null,
	updated_at timestamptz not null default now()
);

alter table public.agent_response_cache
